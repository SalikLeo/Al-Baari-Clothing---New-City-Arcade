-- 1. SETTINGS & APP KEY-VALUE STORE
CREATE TABLE IF NOT EXISTS settings (
  key TEXT PRIMARY KEY,
  value TEXT,
  branch_id TEXT DEFAULT 'b1',
  updated_at TIMESTAMPTZ DEFAULT NOW()
);

CREATE TABLE IF NOT EXISTS app_kv_store (
  key TEXT PRIMARY KEY,
  value TEXT,
  branch_id TEXT DEFAULT 'b1',
  updated_at TIMESTAMPTZ DEFAULT NOW()
);

-- 2. CATEGORY LABELS & PRODUCT UNITS
CREATE TABLE IF NOT EXISTS category_labels (
  id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  slug TEXT UNIQUE NOT NULL,
  label TEXT NOT NULL,
  created_at TIMESTAMPTZ DEFAULT NOW()
);

CREATE TABLE IF NOT EXISTS product_units (
  id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  name TEXT UNIQUE NOT NULL
);

-- 3. COMPANIES (SUPPLIERS / VENDORS)
CREATE TABLE IF NOT EXISTS companies (
  id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  name TEXT NOT NULL,
  description TEXT,
  amount NUMERIC DEFAULT 0,
  phone TEXT,
  email TEXT,
  address TEXT,
  branch_id TEXT DEFAULT 'b1',
  created_at TIMESTAMPTZ DEFAULT NOW()
);
CREATE INDEX IF NOT EXISTS idx_companies_name ON companies(name);
CREATE INDEX IF NOT EXISTS idx_companies_branch ON companies(branch_id);

-- 4. CUSTOMERS (KHATA / ACCOUNTS)
CREATE TABLE IF NOT EXISTS customers (
  id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  name TEXT NOT NULL,
  description TEXT,
  amount NUMERIC DEFAULT 0,
  phone TEXT,
  email TEXT,
  address TEXT,
  branch_id TEXT DEFAULT 'b1',
  created_at TIMESTAMPTZ DEFAULT NOW()
);
CREATE INDEX IF NOT EXISTS idx_customers_name ON customers(name);
CREATE INDEX IF NOT EXISTS idx_customers_phone ON customers(phone);
CREATE INDEX IF NOT EXISTS idx_customers_branch ON customers(branch_id);

-- 5. SHOPS / OUTLETS
CREATE TABLE IF NOT EXISTS shops (
  id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  name TEXT NOT NULL,
  owner_name TEXT,
  phone TEXT,
  address TEXT,
  city TEXT DEFAULT 'Wah Cantt',
  amount NUMERIC DEFAULT 0,
  notes TEXT,
  branch_id TEXT DEFAULT 'b1',
  created_at TIMESTAMPTZ DEFAULT NOW()
);
CREATE INDEX IF NOT EXISTS idx_shops_branch ON shops(branch_id);

-- 6. UNIFIED PRODUCTS TABLE
CREATE TABLE IF NOT EXISTS products (
  id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  category_slug TEXT NOT NULL,
  item_name TEXT NOT NULL,
  description TEXT,
  current_stock NUMERIC DEFAULT 0,
  unit TEXT DEFAULT 'pcs',
  cost_price NUMERIC DEFAULT 0,
  retail_price NUMERIC DEFAULT 0,
  wholesale_cost_price NUMERIC DEFAULT 0,
  wholesale_price NUMERIC DEFAULT 0,
  company_id BIGINT REFERENCES companies(id) ON DELETE SET NULL,
  barcode TEXT,
  pieces_per_carton INTEGER DEFAULT 12,
  branch_id TEXT DEFAULT 'b1',
  legacy_id BIGINT,
  created_at TIMESTAMPTZ DEFAULT NOW()
);
CREATE INDEX IF NOT EXISTS idx_products_cat_branch ON products(category_slug, branch_id);
CREATE INDEX IF NOT EXISTS idx_products_barcode ON products(barcode);
CREATE INDEX IF NOT EXISTS idx_products_item_name ON products(item_name);
CREATE INDEX IF NOT EXISTS idx_products_company ON products(company_id);
CREATE INDEX IF NOT EXISTS idx_products_legacy ON products(category_slug, legacy_id);

-- 7. FAVORITES
CREATE TABLE IF NOT EXISTS favorites (
  id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  category_slug TEXT NOT NULL,
  product_id BIGINT NOT NULL,
  branch_id TEXT DEFAULT 'b1',
  created_at TIMESTAMPTZ DEFAULT NOW(),
  UNIQUE(category_slug, product_id, branch_id)
);
CREATE INDEX IF NOT EXISTS idx_favorites_lookup ON favorites(category_slug, product_id);

-- 8. PRODUCT RATE & STOCK PURCHASE HISTORY
CREATE TABLE IF NOT EXISTS product_rate_history (
  id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  category_slug TEXT,
  product_id BIGINT,
  item_name TEXT,
  old_stock NUMERIC DEFAULT 0,
  added_qty NUMERIC DEFAULT 0,
  new_stock NUMERIC DEFAULT 0,
  old_cost_price NUMERIC DEFAULT 0,
  purchase_price NUMERIC DEFAULT 0,
  new_cost_price NUMERIC DEFAULT 0,
  retail_price NUMERIC DEFAULT 0,
  wholesale_price NUMERIC DEFAULT 0,
  source TEXT,
  notes TEXT,
  branch_id TEXT DEFAULT 'b1',
  created_at TIMESTAMPTZ DEFAULT NOW()
);
CREATE INDEX IF NOT EXISTS idx_prh_cat_prod ON product_rate_history(category_slug, product_id);
CREATE INDEX IF NOT EXISTS idx_prh_branch ON product_rate_history(branch_id);

-- 9. PROPOSALS (SALES INVOICES)
CREATE TABLE IF NOT EXISTS proposals (
  id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  proposal_number TEXT NOT NULL,
  customer_name TEXT,
  location TEXT,
  phone TEXT,
  date TEXT,
  retail_total NUMERIC DEFAULT 0,
  cost_total NUMERIC DEFAULT 0,
  profit NUMERIC DEFAULT 0,
  status TEXT DEFAULT 'active',
  received_amount NUMERIC DEFAULT 0,
  discount NUMERIC DEFAULT 0,
  seller_name TEXT,
  payment_method TEXT DEFAULT 'Cash',
  tax_percent NUMERIC DEFAULT 0,
  tax_amount NUMERIC DEFAULT 0,
  subtotal NUMERIC DEFAULT 0,
  sale_mode TEXT DEFAULT 'retail',
  shop_id BIGINT,
  shop_name TEXT,
  shop_address TEXT,
  salesman_name TEXT,
  salesman_contact TEXT,
  booking_day TEXT,
  delivery_day TEXT,
  branch_id TEXT DEFAULT 'b1',
  created_at TIMESTAMPTZ DEFAULT NOW()
);
CREATE INDEX IF NOT EXISTS idx_proposals_number ON proposals(proposal_number);
CREATE INDEX IF NOT EXISTS idx_proposals_cust_name ON proposals(customer_name);
CREATE INDEX IF NOT EXISTS idx_proposals_date ON proposals(date);
CREATE INDEX IF NOT EXISTS idx_proposals_branch ON proposals(branch_id);

-- 10. PROPOSAL ITEMS (INVOICE LINE ITEMS)
CREATE TABLE IF NOT EXISTS proposal_items (
  id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  proposal_id BIGINT REFERENCES proposals(id) ON DELETE CASCADE,
  item_id BIGINT,
  section TEXT,
  description TEXT,
  qty NUMERIC DEFAULT 0,
  unit_cost NUMERIC DEFAULT 0,
  unit_retail NUMERIC DEFAULT 0,
  unit_discounted NUMERIC DEFAULT 0,
  unit TEXT DEFAULT 'pcs',
  line_cost NUMERIC DEFAULT 0,
  line_retail NUMERIC DEFAULT 0,
  line_profit NUMERIC DEFAULT 0
);
CREATE INDEX IF NOT EXISTS idx_proposal_items_pid ON proposal_items(proposal_id);
CREATE INDEX IF NOT EXISTS idx_proposal_items_sec_item ON proposal_items(section, item_id);

-- 11. EXPENSE CATEGORIES & EXPENSES
CREATE TABLE IF NOT EXISTS expense_categories (
  id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  name TEXT UNIQUE NOT NULL
);

CREATE TABLE IF NOT EXISTS expenses (
  id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  date TEXT,
  category TEXT,
  amount NUMERIC DEFAULT 0,
  description TEXT,
  paid_by TEXT,
  notes TEXT,
  branch_id TEXT DEFAULT 'b1',
  created_at TIMESTAMPTZ DEFAULT NOW()
);
CREATE INDEX IF NOT EXISTS idx_expenses_date ON expenses(date);
CREATE INDEX IF NOT EXISTS idx_expenses_branch ON expenses(branch_id);

-- 12. EMPLOYEES
CREATE TABLE IF NOT EXISTS employees (
  id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  full_name TEXT NOT NULL,
  role TEXT,
  phone TEXT,
  email TEXT,
  date_joined TEXT,
  salary NUMERIC DEFAULT 0,
  status TEXT DEFAULT 'Active',
  notes TEXT,
  date_inactive TEXT,
  branch_id TEXT DEFAULT 'b1',
  created_at TIMESTAMPTZ DEFAULT NOW()
);
CREATE INDEX IF NOT EXISTS idx_employees_status ON employees(status);
CREATE INDEX IF NOT EXISTS idx_employees_branch ON employees(branch_id);

